/**
 * @brief Moyenne d'une voie sur les ADC_NB_SCAN derniers scans.
 * @param ch voie 0..ADC_NB_CH-1 (IN0..IN7)
 * @return moyenne arrondie, 0..4095
 */
static uint16_t ADC_mean(uint32_t ch)
{
  uint32_t sum = 0;
  for (uint32_t i = ch; i < ADC_NB_SCAN * ADC_NB_CH; i += ADC_NB_CH)
  {
    sum += adc_dma[i];
  }
  return (uint16_t)((sum + ADC_NB_SCAN / 2) / ADC_NB_SCAN);
}

/**
 * @brief Émission d'une valeur décimale suivie d'un caractère de fin (' ' ou '\n').
 */
static void UART_send_value(uint32_t value, char end)
{
  char buf[12];
  uint32_t i = sizeof(buf);
  buf[--i] = end;
  do
  {
    buf[--i] = (char)('0' + value % 10);
    value /= 10;
  } while (value != 0);
  HAL_UART_Transmit(&huart1, (uint8_t *)&buf[i], sizeof(buf) - i, 10);
}

/**
 * @brief Émission d'une chaîne terminée par 0.
 */
static void UART_send_str(const char *str)
{
  uint16_t len = 0;
  while (str[len] != 0)
  {
    len++;
  }
  HAL_UART_Transmit(&huart1, (uint8_t *)str, len, 10);
}

/**
 * @brief Traitement d'une commande : un caractère, sensible à la casse, protocole identique au firmware d'origine
 *        du module (v1.4) :
 *        - '0'..'9' : valeur de la voie, 0..4095, terminée par '\n' ;
 *        - 'A' : toutes les voies, chacune suivie d'un espace, puis '\n' ;
 *        - 'V' : identification du firmware, terminée par '\n' ;
 *        - tout autre caractère (dont '\r', '\n', minuscules, voie non convertie) : "?\n".
 */
static void CMD_process(uint8_t c)
{
  if (c >= '0' && c < '0' + ADC_NB_CH)
  {
    UART_send_value(ADC_mean(c - '0'), '\n');
  }
  else if (c == 'A')
  {
    for (uint32_t ch = 0; ch < ADC_NB_CH; ch++)
    {
      UART_send_value(ADC_mean(ch), ' ');
    }
    UART_send_str("\n");
  }
  else if (c == 'V')
  {
    UART_send_str(USB_ADC_VERSION "\n");
  }
  else
  {
    UART_send_str("?\n");
  }
}
